# Stan program (typed IR) -> generative R script.
#
# Modes
#   prior_predictive      parameters drawn from their priors, observed data drawn
#                         from the likelihood
#   posterior_predictive  parameters fixed at one posterior draw, observed data drawn
#   posterior_density     parameters fixed at one posterior draw; `out` holds the
#                         pointwise density/mass of each observed data element
#   prior_density         parameters drawn from the prior; pointwise densities
#
# The script reads the data block's variables from a list called `dat` and leaves
# every top-level Stan variable in a list called `out`.

stan2r_modes <- c("prior_predictive", "posterior_predictive", "posterior_density", "prior_density")

#' Translate a Stan program into a generative R script.
#'
#' @param program a `stan2r_program` (from [stan_program()]) or Stan source.
#' @param mode one of "prior_predictive", "posterior_predictive",
#'   "posterior_density", "prior_density".
#' @param dat optional list of data; used to check that required data exist and
#'   to decide which simulated outcomes need allocating.
#' @param samps posterior draws (data frame with CmdStan-style column names such
#'   as `theta[1]` or `theta.1.`); required by the posterior modes.
#' @param sample_index row of `samps` used by the posterior modes.
#' @return the R script as a single string, with attribute `warnings`.
#' @export
stan2r <- function(program, mode = stan2r_modes, dat = NULL, samps = NULL, sample_index = 1) {
  if (!inherits(program, "stan2r_program")) program <- stan_program(program)
  mode <- match.arg(mode)
  ctx <- new_translation_context(program, mode, dat, samps, sample_index)
  analyse_model(ctx)

  sections <- list()
  add <- function(label, lines) sections[[length(sections) + 1]] <<- list(label = label, lines = lines)

  fun_lines <- translate_functions(ctx)
  add("data", translate_data_block(ctx))
  add("transformed data", tr_stmts(program$blocks[["transformed data"]], ctx, 0))
  add("parameters", translate_parameters(ctx))
  for (sec in translate_tp_and_model(ctx)) add(sec$label, sec$lines)
  if (length(ctx$improper)) {
    bad <- ctx$improper[[1]]
    stan2r_unsupported(sprintf("parameter '%s' has no prior statement, so its prior is improper and cannot be simulated",
                               bad$name), bad$line, "parameter without a prior")
  }
  add("generated quantities", tr_stmts(program$blocks[["generated quantities"]], ctx, 0))
  # functions can be referenced from any block, so their translation comes last
  fun_lines <- c(finish_functions(ctx, fun_lines), unlist(ctx$derived_functions, use.names = FALSE))

  body <- character(0)
  if (length(fun_lines)) body <- c(body, section_header("functions"), fun_lines)
  prev <- ""
  for (sec in sections) {
    if (!length(sec$lines)) next
    if (sec$label != prev) body <- c(body, section_header(sec$label))
    body <- c(body, sec$lines)
    prev <- sec$label
  }
  body <- c(body, section_header("output"), output_lines(ctx))

  header <- c(sprintf("# R translation of a Stan program, generated by Stan2R (%s).", mode_description(mode)),
              "# Reads data from the list `dat`; every top-level Stan variable is returned in `out`.")
  helpers <- helper_source(ctx$helpers)
  if (length(helpers)) header <- c(header, "", "# helper functions", helpers)
  code <- paste(c(header, body, ""), collapse = "\n")
  code <- gsub("\n{3,}", "\n\n", code)
  for (w in unique(ctx$warnings)) warning(w, call. = FALSE)
  attr(code, "warnings") <- unique(ctx$warnings)
  code
}

#' Convert a Stan model to R code (original Stan2R interface).
#'
#' @param stan_code Stan program lines (e.g. from readLines()).
#' @param dat list of data (see [stan2r()]).
#' @param samps posterior draws for the posterior modes.
#' @param output_file optional path to write the R code to.
#' @param sample_index row of `samps` to use.
#' @param post_pred_sim TRUE for posterior modes (parameters from `samps`), FALSE to
#'   draw parameters from the prior.
#' @param sim TRUE to simulate observed data, FALSE to compute their densities.
#' @export
parse_Stan <- function(stan_code, dat = NA, samps = NA, output_file = NA, sample_index = 1,
                       post_pred_sim = TRUE, sim = TRUE) {
  mode <- if (sim && !post_pred_sim) "prior_predictive" else if (sim) "posterior_predictive"
          else if (post_pred_sim) "posterior_density" else "prior_density"
  if (!is.list(dat)) dat <- NULL
  if (!is.data.frame(samps) && !is.matrix(samps)) samps <- NULL
  code <- stan2r(stan_program(stan_code), mode, dat = dat, samps = samps, sample_index = sample_index)
  if (!is.na(output_file)) writeLines(code, output_file)
  code
}

mode_description <- function(mode) {
  switch(mode, prior_predictive = "prior predictive simulation",
         posterior_predictive = "posterior predictive simulation",
         posterior_density = "pointwise posterior predictive densities",
         prior_density = "pointwise densities with parameters drawn from the prior")
}

section_header <- function(label) {
  title <- paste0("#### ", label, " ####")
  rule <- paste0("#", strrep("~", nchar(title) - 2), "#")
  c("", rule, title, rule, "")
}

new_translation_context <- function(program, mode, dat, samps, sample_index) {
  ctx <- new.env(parent = emptyenv())
  ctx$program <- program
  ctx$mode <- mode
  ctx$sim <- mode %in% c("prior_predictive", "posterior_predictive")
  ctx$posterior <- mode %in% c("posterior_predictive", "posterior_density")
  ctx$dat_names <- if (is.list(dat)) names(dat) else NULL
  ctx$samps <- samps
  ctx$sample_index <- sample_index
  ctx$helpers <- character(0)
  ctx$user_calls <- character(0)
  ctx$warnings <- character(0)
  ctx$line <- NA_integer_
  ctx$counter <- 0L
  ctx$derived_functions <- list()
  ctx$improper <- list()
  ctx$derived_outcome <- NULL
  ctx$observed <- character(0)
  ctx$accumulators <- list()
  sy <- program$symbols
  ctx$sym <- if (nrow(sy)) setNames(lapply(seq_len(nrow(sy)), function(i) as.list(sy[i, ])), sy$name) else list()
  for (nm in names(ctx$sym)) ctx$sym[[nm]]$decl <- sy$decl[[which(sy$name == nm)]]
  if (ctx$posterior && is.null(samps)) {
    stop("Stan2R: the ", mode, " mode needs posterior draws in `samps`", call. = FALSE)
  }
  ctx
}

sym_role <- function(ctx, name) {
  s <- ctx$sym[[name]]
  if (is.null(s)) "scoped" else s$role
}

ind <- function(depth) strrep("  ", depth)

#### model analysis ####

# base variable name of a Var/Index chain, or NULL for other expressions
outcome_base <- function(e) {
  e <- unwrap_reshape(e)
  while (identical(e$node, "Index")) e <- e$arg
  if (identical(e$node, "Var")) e$name else NULL
}

reshape_functions <- c("to_vector", "to_row_vector", "to_array_1d")

# to_vector(X) ~ ... draws all of X; returns the Var/Index inside such a call
unwrap_reshape <- function(e) {
  if (identical(e$node, "Call") && e$name %in% reshape_functions && length(e$args) == 1 &&
      e$args[[1]]$node %in% c("Var", "Index")) e$args[[1]] else e
}

# lvalue code for a sampled outcome; whole containers are filled in place (x[] <- ...)
outcome_lvalue <- function(outcome, ctx) {
  target <- unwrap_reshape(outcome)
  reshaped <- !identical(target, outcome)
  code <- lvalue_code(target, ctx)
  list(code = code, fill = if (reshaped || type_rank(target$type) >= 2) paste0(code, "[]") else code,
       reshaped = reshaped, target = target)
}

is_lp_call <- function(e) {
  if (!identical(e$node, "Call")) return(FALSE)
  if (e$origin == "UserDefined") return(e$suffix %in% c("FnLpdf", "FnLpmf"))
  parts <- split_dist_name(e$name)
  !is.null(parts) && parts$suffix %in% c("lpdf", "lupdf", "lpmf", "lupmf")
}

lp_call_dist <- function(e) {
  if (e$origin == "UserDefined") sub("_(lpdf|lpmf)$", "", e$name) else split_dist_name(e$name)$dist
}

# collect nodes of an IR tree that satisfy pred (not descending into matches)
ir_find <- function(x, pred) {
  if (!is.list(x)) return(list())
  if (!is.null(x$node) && pred(x)) return(list(x))
  unlist(lapply(x, ir_find, pred = pred), recursive = FALSE)
}

expr_vars <- function(x) unique(vapply(ir_find(x, function(n) n$node == "Var"), `[[`, "", "name"))

walk_stmts <- function(stmts, fn) {
  for (s in stmts) {
    fn(s)
    kids <- switch(s$node, Block = , Profile = s$stmts, For = , ForEach = , While = list(s$body),
                   If = c(list(s$then), if (!is.null(s$otherwise)) list(s$otherwise)), list())
    walk_stmts(kids, fn)
  }
}

drawable_role <- function(role) role %in% c("param", "data", "tdata")

analyse_model <- function(ctx) {
  model <- ctx$program$blocks$model
  outcomes <- character(0)
  note_outcome <- function(e) {
    b <- outcome_base(e)
    if (!is.null(b)) outcomes <<- c(outcomes, b)
  }
  walk_stmts(model, function(s) {
    if (s$node == "Tilde") note_outcome(s$arg)
    for (call in ir_find(s[setdiff(names(s), c("stmts", "body", "then", "otherwise"))], is_lp_call)) note_outcome(call$args[[1]])
  })
  acc_targets <- accumulator_targets(model, "TargetPE")
  roles <- vapply(unique(outcomes), function(b) sym_role(ctx, b), "")
  ctx$observed <- names(roles)[roles %in% c("data", "tdata")]
  ctx$drawn_params <- names(roles)[roles == "param"]

  ctx$accumulators <- find_accumulators(model, acc_targets)
  invisible(NULL)
}

#### statements ####

tr_stmts <- function(stmts, ctx, depth) {
  out <- character(0)
  for (s in stmts) out <- c(out, tr_stmt_annotated(s, ctx, depth))
  out
}

comment_lines <- function(comments, depth) {
  out <- character(0)
  for (cm in comments) {
    if (isTRUE(cm$blank_before)) out <- c(out, "")
    out <- c(out, paste0(ind(depth), "# ", cm$text))
  }
  sub("# $", "#", out)
}

tr_stmt_annotated <- function(s, ctx, depth) {
  ctx$line <- s$line
  code <- tr_stmt(s, ctx, depth)
  lead <- character(0)
  if (isTRUE(s$blank_before) && !length(s$comments_before)) lead <- ""
  lead <- c(lead, comment_lines(s$comments_before, depth))
  if (length(s$comment_after) && length(code)) {
    code[length(code)] <- paste0(code[length(code)], "  # ", paste(s$comment_after, collapse = " "))
  }
  c(lead, code)
}

tr_body <- function(s, ctx, depth) {
  if (identical(s$node, "Block")) {
    c(tr_stmts(s$stmts, ctx, depth), comment_lines(s$closing_comments, depth))
  } else {
    tr_stmt_annotated(s, ctx, depth)
  }
}

tr_stmt <- function(s, ctx, depth) {
  i <- ind(depth)
  switch(s$node,
    Decl = tr_decl(s, ctx, depth),
    Assign = tr_assign(s, ctx, depth),
    Tilde = tr_sampling(s, ctx, depth, outcome = s$arg, dist = s$dist, origin = s$origin,
                        suffix = s$suffix, args = s$args, truncation = s$truncation),
    TargetPE = tr_target(s, ctx, depth),
    JacobianPE = paste0(i, "# (jacobian increment, not needed for simulation: ", stan_stmt_text(s, ctx), ")"),
    For = {
      lo <- translate_expr(s$lower, ctx)
      up <- translate_expr(s$upper, ctx)
      c(paste0(i, "for (", r_name(s$var), " in ", range_code(lo, up, ctx), ") {"),
        tr_body(s$body, ctx, depth + 1), paste0(i, "}"))
    },
    ForEach = tr_foreach(s, ctx, depth),
    While = c(paste0(i, "while (", translate_expr(s$cond, ctx)$code, ") {"),
              tr_body(s$body, ctx, depth + 1), paste0(i, "}")),
    If = tr_if(s, ctx, depth),
    Block = c(tr_stmts(s$stmts, ctx, depth), comment_lines(s$closing_comments, depth)),
    Profile = c(paste0(i, "# profile(\"", s$name, "\")"), tr_stmts(s$stmts, ctx, depth)),
    Print = if (length(ir_find(s$items, function(n) n$node == "GetTarget"))) {
      paste0(i, "# (print of target() omitted: ", stan_stmt_text(s, ctx), ")")
    } else paste0(i, "cat(", printables_code(s$items, ctx), ", \"\\n\", sep = \"\")"),
    Reject = , FatalError = paste0(i, "stop(", printables_code(s$items, ctx), ", call. = FALSE)"),
    Break = paste0(i, "break"),
    Continue = paste0(i, "next"),
    Return = {
      if (!is.null(ctx$derived_outcome) && !is.null(s$value)) {
        c(tr_target(c(s[c("line", "span")], list(node = "TargetPE", expr = s$value)), ctx, depth),
          paste0(i, "return(", r_name(ctx$derived_outcome), ")"))
      } else {
        paste0(i, if (is.null(s$value)) "return(invisible(NULL))" else paste0("return(", translate_expr(s$value, ctx)$code, ")"))
      }
    },
    Skip = character(0),
    NRFunApp = {
      call <- list(node = "Call", name = s$name, origin = s$origin, suffix = s$suffix, conditional = FALSE,
                   args = s$args, type = list(base = "void", adims = 0L), ad = "DataOnly")
      if (s$origin == "UserDefined") paste0(i, translate_call(call, ctx)$code)
      else stan2r_unsupported(sprintf("statement call %s()", s$name), s$line, paste0("function ", s$name))
    },
    stan2r_unsupported(sprintf("statement %s", s$node), s$line, s$node))
}

printables_code <- function(items, ctx) {
  paste(vapply(items, function(it) translate_expr(it, ctx)$code, ""), collapse = ", ")
}

tr_if <- function(s, ctx, depth) {
  i <- ind(depth)
  out <- c(paste0(i, "if (", translate_expr(s$cond, ctx)$code, ") {"), tr_body(s$then, ctx, depth + 1))
  other <- s$otherwise
  while (!is.null(other)) {
    if (identical(other$node, "If")) {
      ctx$line <- other$line
      out <- c(out, paste0(i, "} else if (", translate_expr(other$cond, ctx)$code, ") {"),
               tr_body(other$then, ctx, depth + 1))
      other <- other$otherwise
    } else {
      out <- c(out, paste0(i, "} else {"), tr_body(other, ctx, depth + 1))
      other <- NULL
    }
  }
  c(out, paste0(i, "}"))
}

tr_foreach <- function(s, ctx, depth) {
  i <- ind(depth)
  it <- translate_expr(s$iter, ctx)
  t <- s$iter$type
  if (type_rank(t) <= 1 || (t$adims == 0 && t$base == "matrix")) {
    seq_code <- if (t$base == "matrix" && t$adims == 0) paste0("as.vector(", it$code, ")") else it$code
    return(c(paste0(i, "for (", r_name(s$var), " in ", seq_code, ") {"), tr_body(s$body, ctx, depth + 1), paste0(i, "}")))
  }
  ctx$counter <- ctx$counter + 1L
  k <- paste0("i", ctx$counter, "__")
  rest <- strrep(", ", type_rank(t) - 1)
  c(paste0(i, "for (", k, " in seq_len(dim(", it$code, ")[1])) {"),
    paste0(ind(depth + 1), r_name(s$var), " <- ", wrap(it, PREC_ATOM), "[", k, rest, "]"),
    tr_body(s$body, ctx, depth + 1), paste0(i, "}"))
}

# R code that allocates an object of a declared Stan type
alloc_code <- function(stype, ctx) {
  dims <- vapply(c(stype$array_dims, stype$dims), function(d) translate_expr(d, ctx)$code, "")
  na <- if (stype$base == "int") "NA_integer_" else "NA_real_"
  if (stype$base == "tuple") stan2r_unsupported("tuples", ctx$line, "tuples")
  if (grepl("complex", stype$base)) stan2r_unsupported("complex numbers", ctx$line, "complex numbers")
  switch(as.character(min(length(dims), 3)),
         "0" = na,
         "1" = paste0("rep(", na, ", ", dims, ")"),
         "2" = paste0("matrix(", na, ", ", dims[1], ", ", dims[2], ")"),
         "3" = paste0("array(", na, ", dim = c(", paste(dims, collapse = ", "), "))"))
}

tr_decl <- function(s, ctx, depth) {
  out <- character(0)
  for (v in s$vars) {
    rhs <- if (is.null(v$init)) alloc_code(s$stype, ctx) else translate_expr(v$init, ctx)$code
    out <- c(out, paste0(ind(depth), r_name(v$name), " <- ", rhs))
    acc <- ctx$accumulators[[v$name]]
    if (!is.null(acc) && accumulator_active(acc, ctx)) {
      out <- c(out, paste0(ind(depth), v$name, "_draws__ <- list()"))
    }
  }
  out
}

lvalue_code <- function(lhs, ctx) translate_lvalue(lhs, ctx)

translate_lvalue <- function(l, ctx) {
  if (l$node == "Var") return(r_name(l$name))
  if (l$node == "Index") {
    base <- translate_lvalue(l$arg, ctx)
    rank <- type_rank(l$arg$type)
    ic <- index_codes(l$indices, base, rank, ctx)
    return(paste0(base, "[", paste(ic$codes, collapse = ", "), "]"))
  }
  stan2r_unsupported("tuple assignment", ctx$line, "tuples")
}

tr_assign <- function(s, ctx, depth) {
  i <- ind(depth)
  lhs <- lvalue_code(s$lhs, ctx)
  acc <- ctx$accumulators[[outcome_base(s$lhs) %||% ""]]
  rhs_ir <- s$rhs
  extra <- character(0)
  if (!is.null(acc) && accumulator_active(acc, ctx)) {
    split <- split_weight(rhs_ir, ctx)
    if (!is.null(split)) {
      is_param <- sym_role(ctx, acc$base) == "param"
      draw <- sampling_draw_code(split$call$args[[1]], lp_call_dist(split$call), split$call$origin,
                                 split$call$args[-1], NULL, ctx, implicit_bounds = is_param && acc$reducer == "log_sum_exp")
      if (acc$reducer == "log_sum_exp") {
        acc_index <- lvalue_index_code(s$lhs, ctx)
        extra <- paste0(i, outcome_base(s$lhs), "_draws__[[", acc_index, "]] <- ", draw$rhs)
      } else {
        extra <- paste0(i, draw$lhs, " <- ", draw$rhs)
        draw$log_mass <- NULL
      }
      weight <- if (is.null(split$weight)) "0" else translate_expr(split$weight, ctx)$code
      weight <- component_weight(weight, draw, ctx)
      if (weight == "0") {
        if (s$op != "=") return(extra)
        return(c(paste0(i, lhs, " <- 0"), extra))
      }
      if (s$op == "=") return(c(paste0(i, lhs, " <- ", weight), extra))
      op <- sub("=$", "", s$op)
      return(c(paste0(i, lhs, " <- ", lhs, " ", op, " ", if (grepl("^[A-Za-z0-9_.]+$", weight)) weight else paste0("(", weight, ")")), extra))
    }
  }
  if (s$op == "=") {
    rhs <- translate_expr(rhs_ir, ctx)$code
  } else {
    op <- sub("=$", "", s$op)
    lhs_expr <- s$lhs
    rhs <- translate_binop(list(node = "BinOp", lhs = lhs_expr, op = op, rhs = rhs_ir, type = s$lhs$type), ctx)$code
  }
  c(paste0(i, lhs, " <- ", rhs), extra)
}

lvalue_index_code <- function(l, ctx) {
  if (l$node != "Index" || length(l$indices) != 1 || l$indices[[1]]$kind != "single") {
    stan2r_unsupported("mixture accumulator assigned other than element by element", ctx$line, "mixture accumulator")
  }
  translate_expr(l$indices[[1]]$expr, ctx)$code
}

# an accumulator changes generated code only when its outcome is simulated
accumulator_active <- function(acc, ctx) {
  role <- sym_role(ctx, acc$base)
  ctx$sim && role %in% c("data", "tdata") || !ctx$posterior && role == "param"
}

# split `weight + D_lpdf(y | ...)` into the weight (or NULL) and the density call
split_weight <- function(e, ctx) {
  terms <- sum_terms(e)
  is_lp <- vapply(terms, function(t) t$sign > 0 && is_lp_call(t$expr), logical(1))
  if (sum(is_lp) != 1) {
    if (length(ir_find(e, is_lp_call))) {
      stan2r_unsupported("density term that is not a single added term of the expression", ctx$line,
                         "density inside a larger expression")
    }
    return(NULL)
  }
  call <- terms[[which(is_lp)]]$expr
  rest <- terms[!is_lp]
  if (!length(rest)) return(list(weight = NULL, call = call))
  if (length(ir_find(rest, is_lp_call))) {
    stan2r_unsupported("density term that is not a single added term of the expression", ctx$line,
                       "density inside a larger expression")
  }
  list(weight = rebuild_sum(rest), call = call)
}

# flatten a +/- tree into signed terms
sum_terms <- function(e, sign = 1) {
  if (identical(e$node, "BinOp") && e$op %in% c("+", "-") && !isTRUE(e$paren) &&
      type_rank(e$type) == type_rank(e$lhs$type)) {
    return(c(sum_terms(e$lhs, sign), sum_terms(e$rhs, if (e$op == "-") -sign else sign)))
  }
  list(list(expr = e, sign = sign))
}

rebuild_sum <- function(terms) {
  out <- terms[[1]]$expr
  if (terms[[1]]$sign < 0) out <- list(node = "PrefixOp", op = "-", arg = out, type = out$type, ad = out$ad)
  for (t in terms[-1]) {
    out <- list(node = "BinOp", lhs = out, op = if (t$sign > 0) "+" else "-", rhs = t$expr,
                type = out$type, ad = out$ad)
  }
  out
}

#### sampling statements ####

sampling_action <- function(role, ctx) {
  if (role %in% c("data", "tdata")) return(if (ctx$sim) "draw" else "density")
  if (role == "param") return(if (ctx$posterior) "skip" else "draw")
  if (role == "tparam" && ctx$posterior) return("skip")
  "error"
}

tr_sampling <- function(s, ctx, depth, outcome, dist, origin, suffix, args, truncation) {
  i <- ind(depth)
  base <- outcome_base(outcome)
  if (is.null(base)) {
    deps <- expr_vars(outcome)
    if (ctx$posterior && !any(deps %in% ctx$observed)) {
      return(paste0(i, "# (prior term on an expression, fixed by the posterior draw: ", stan_stmt_text(s, ctx), ")"))
    }
    stan2r_unsupported(sprintf("sampling statement with an expression on the left-hand side (%s)",
                               stan_expr_text(outcome)), s$line, "expression on left of ~")
  }
  role <- sym_role(ctx, base)
  action <- sampling_action(role, ctx)
  if (action == "skip") {
    return(paste0(i, "# (prior, fixed by the posterior draw: ", stan_stmt_text(s, ctx), ")"))
  }
  if (action == "error") {
    what <- switch(role, tparam = "transformed parameter", local = "model-block local variable",
                   scoped = "local variable", role)
    stan2r_unsupported(sprintf("sampling statement on %s '%s', which cannot be simulated forward", what, base),
                       s$line, paste("~ on", what))
  }
  if (action == "draw") {
    draw <- sampling_draw_code(outcome, dist, origin, args, truncation, ctx, implicit_bounds = role == "param")
    return(paste0(i, draw$lhs, " <- ", draw$rhs))
  }
  density_code <- sampling_density_code(outcome, dist, origin, suffix, args, truncation, ctx)
  ol <- outcome_lvalue(outcome, ctx)
  target <- paste0("log_density__$", base, substring(ol$fill, nchar(r_name(base)) + 1))
  paste0(i, target, " <- add_log_density(", target, ", ", density_code, ")")
}

# R code drawing `outcome` from a distribution; returns list(lhs, rhs)
sampling_draw_code <- function(outcome, dist, origin, args, truncation, ctx, implicit_bounds = FALSE) {
  ol <- outcome_lvalue(outcome, ctx)
  lhs <- ol$code
  rank <- type_rank(outcome$type)
  base <- outcome_base(outcome)
  if (ol$reshaped && any(vapply(args, function(a) type_rank(a$type) > 0, logical(1))) &&
      ol$target$type$adims >= 1 && type_rank(ol$target$type) >= 2) {
    stan2r_unsupported(sprintf("%s of a multi-dimensional array with element-specific arguments", stan_expr_text(outcome)),
                       ctx$line, "reshaped outcome of an array")
  }
  if (origin == "UserDefined") {
    rng <- paste0(dist, "_rng")
    if (is.null(ctx$program$functions[[rng]])) {
      if (!is.null(truncation)) stan2r_unsupported("truncation of a user-defined distribution", ctx$line, "truncation")
      fn <- derive_udf_draw(dist, ctx)
      vals <- vapply(args, function(a) translate_expr(a, ctx)$code, "")
      return(list(lhs = ol$fill, rhs = paste0(fn, "(", paste(c(lhs, vals), collapse = ", "), ")")))
    }
    if (!is.null(truncation)) stan2r_unsupported("truncation of a user-defined distribution", ctx$line, "truncation")
    ctx$user_calls <- unique(c(ctx$user_calls, rng))
    vals <- vapply(args, function(a) translate_expr(a, ctx)$code, "")
    return(list(lhs = ol$fill, rhs = paste0(rng, "(", paste(vals, collapse = ", "), ")")))
  }
  if (is.null(stan_distributions()[[dist]]) && is.na(stan_glm_distributions[dist])) {
    stan2r_unsupported(sprintf("distribution %s", dist), ctx$line, paste0("distribution ", dist))
  }
  da <- distribution_args(dist, args, ctx)
  sym <- ctx$sym[[base]]
  transform <- if (!is.null(sym) && implicit_bounds) sym$decl$transform else list(kind = "none")
  if (isTRUE(da$def$multivariate)) {
    if (!is.null(truncation)) stan2r_unsupported("truncation of a multivariate distribution", ctx$line, "truncation")
    check_constraint_match(transform$kind, da$name, ctx, base)
    if (ol$reshaped) stan2r_unsupported("reshaped outcome of a multivariate distribution", ctx$line, "reshaped outcome")
    rhs <- fill_template(dist_template(da, "r", ctx), c(da$values, list(like = lhs)))
    return(list(lhs = lhs, rhs = rhs))
  }
  check_constraint_match(transform$kind, da$name, ctx, base)
  n <- if (rank == 0) "1" else paste0("length(", lhs, ")")
  if (rank == 0 && any(vapply(args, function(a) type_rank(a$type) > 0, logical(1)))) {
    stan2r_unsupported(sprintf("scalar outcome %s with vectorised distribution arguments", stan_expr_text(outcome)),
                       ctx$line, "scalar outcome with vector arguments")
  }
  bounds <- truncation
  implicit <- FALSE
  if (is.null(bounds) && transform$kind %in% c("bounds", "positive_ordered")) {
    bounds <- implicit_truncation(transform, outcome, da, ctx)
    implicit <- !is.null(bounds)
  }
  rhs <- if (is.null(bounds)) {
    fill_template(dist_template(da, "r", ctx), c(da$values, list(n = n)))
  } else {
    if (implicit) check_implicit_truncation(da, args, bounds, base, ctx)
    truncated_draw_code(da, bounds, n, ctx)
  }
  if (transform$kind %in% c("ordered", "positive_ordered")) rhs <- ordered_draw(rhs, args, base, ctx)
  if (transform$kind == "sum_to_zero_vector") rhs <- sum_to_zero_draw(rhs, da, base, ctx)
  # mixture components on a bounded parameter are chosen in proportion to their mass inside the bounds
  log_mass <- if (implicit) truncation_log_mass(da, bounds, ctx) else NULL
  list(lhs = ol$fill, rhs = rhs, log_mass = log_mass)
}

truncation_log_mass <- function(da, bounds, ctx) {
  if (is.null(da$def$p)) return(NA_character_)
  cdf <- function(b) fill_template(da$def$p, c(da$values, list(y = wrap(translate_expr(b, ctx), PREC_ATOM), opts = "")))
  pl <- if (is.null(bounds$lower)) "0" else if (isTRUE(da$def$discrete)) {
    fill_template(da$def$p, c(da$values, list(y = paste0(wrap(translate_expr(bounds$lower, ctx), PREC_ADD), " - 1"), opts = "")))
  } else cdf(bounds$lower)
  pu <- if (is.null(bounds$upper)) "1" else cdf(bounds$upper)
  paste0("log(", pu, " - ", pl, ")")
}

# weight code for a mixture component, including its mass inside a parameter's bounds
component_weight <- function(weight_code, draw, ctx) {
  if (is.null(draw$log_mass)) return(weight_code)
  if (is.na(draw$log_mass)) {
    stan2r_unsupported("mixture component on a bounded parameter whose distribution has no CDF", ctx$line,
                       "mixture on bounded parameter")
  }
  if (identical(weight_code, "0")) draw$log_mass else paste0(weight_code, " + ", draw$log_mass)
}

# constrained parameter types are only simulated from priors that live on that type
check_constraint_match <- function(kind, dist, ctx, base) {
  ok <- switch(kind,
    none = , affine = , bounds = , ordered = , positive_ordered = TRUE,
    simplex = dist == "dirichlet",
    sum_to_zero_vector = dist %in% c("normal", "std_normal"),
    cholesky_factor_corr = dist == "lkj_corr_cholesky",
    corr_matrix = dist == "lkj_corr",
    cov_matrix = dist %in% c("wishart", "inv_wishart"),
    cholesky_factor_cov = dist %in% c("wishart_cholesky", "inv_wishart_cholesky"),
    FALSE)
  if (!ok) {
    stan2r_unsupported(sprintf("%s prior on %s parameter '%s'", dist, kind, base), ctx$line,
                       paste0(dist, " prior on ", kind))
  }
}

# declared bounds as a truncation, unless they coincide with the distribution's support
implicit_truncation <- function(transform, outcome, da, ctx) {
  lower <- if (transform$kind == "positive_ordered") list(node = "Int", value = "0", type = list(base = "int", adims = 0L), ad = "DataOnly") else transform$lower
  upper <- if (transform$kind == "positive_ordered") NULL else transform$upper
  index_bound <- function(b) {
    if (is.null(b) || type_rank(b$type) == 0 || !identical(outcome$node, "Index")) return(b)
    list(node = "Index", arg = b, indices = outcome$indices, type = outcome$type, ad = b$ad)
  }
  lower <- index_bound(lower)
  upper <- index_bound(upper)
  same_as_support <- function(b, s) {
    if (is.null(b)) return(TRUE)
    if (is.numeric(s) || grepl("^-?(Inf|[0-9.]+)$", s)) {
      return(b$node %in% c("Int", "Real") && as.numeric(b$value) == as.numeric(s))
    }
    arg <- da$values[[s]]
    !is.null(arg) && identical(translate_expr(b, ctx)$code, arg$code)
  }
  if (same_as_support(lower, da$def$support[1])) lower <- NULL
  if (same_as_support(upper, da$def$support[2])) upper <- NULL
  if (is.null(lower) && is.null(upper)) return(NULL)
  list(lower = lower, upper = upper)
}

symmetric_families <- c("normal", "std_normal", "student_t", "cauchy", "double_exponential", "logistic")

check_implicit_truncation <- function(da, args, bounds, base, ctx) {
  bound_ad <- any(vapply(Filter(Negate(is.null), bounds), function(b) b$ad != "DataOnly", logical(1)))
  depends <- bound_ad || any(vapply(args, function(a) a$ad != "DataOnly", logical(1)))
  if (!depends) return(invisible(NULL))
  # half-distributions of symmetric families centred at the bound keep a constant normaliser
  centred <- da$name %in% symmetric_families && is.null(bounds$upper) && !is.null(bounds$lower) &&
    bounds$lower$node %in% c("Int", "Real") && as.numeric(bounds$lower$value) == 0 &&
    (da$name == "std_normal" || identical(da$values$mu$code, "0"))
  if (centred && !bound_ad) return(invisible(NULL))
  ctx$warnings <- c(ctx$warnings, sprintf(paste0(
    "Stan2R: the prior for '%s' (line %d) is truncated by its declared bounds, and the truncation's ",
    "normalising constant depends on other parameters. Per-statement truncated draws then differ from ",
    "Stan's joint prior."), base, ctx$line))
}

truncated_draw_code <- function(da, bounds, n, ctx) {
  p_tpl <- da$def$p
  q_tpl <- da$def$q
  lower <- if (!is.null(bounds$lower)) translate_expr(bounds$lower, ctx) else NULL
  upper <- if (!is.null(bounds$upper)) translate_expr(bounds$upper, ctx) else NULL
  if (is.null(p_tpl) || is.null(q_tpl)) {
    ctx_use_helper(ctx, c("rtruncated_reject", template_helpers(da$def$r, da$def$helpers)))
    draw <- fill_template(dist_template(da, "r", ctx), c(da$values, list(n = "n")))
    return(paste0("rtruncated_reject(", n, ", function(n) ", draw, ", ",
                  if (is.null(lower)) "-Inf" else lower$code, ", ", if (is.null(upper)) "Inf" else upper$code, ")"))
  }
  ctx_use_helper(ctx, template_helpers(paste(p_tpl, q_tpl), da$def$helpers))
  cdf <- function(at) fill_template(p_tpl, c(da$values, list(y = at, opts = "")))
  p_lower <- if (is.null(lower)) NULL else cdf(if (isTRUE(da$def$discrete)) paste0(wrap(lower, PREC_ADD), " - 1") else wrap(lower, PREC_ATOM))
  p_upper <- if (is.null(upper)) NULL else cdf(wrap(upper, PREC_ATOM))
  u <- paste0("runif(", n, ")")
  target <- if (!is.null(p_lower) && !is.null(p_upper)) paste0(p_lower, " + (", p_upper, " - ", p_lower, ") * ", u)
            else if (!is.null(p_lower)) paste0(p_lower, " + (1 - ", p_lower, ") * ", u)
            else paste0(p_upper, " * ", u)
  fill_template(q_tpl, c(da$values, list(p = target)))
}

ordered_draw <- function(rhs, args, base, ctx) {
  if (any(vapply(args, function(a) type_rank(a$type) > 0, logical(1)))) {
    ctx$warnings <- c(ctx$warnings, sprintf(paste0(
      "Stan2R: ordered parameter '%s' (line %d) has element-specific prior arguments; sorting independent ",
      "draws only reproduces Stan's prior when the elements are exchangeable."), base, ctx$line))
  }
  paste0("sort(", rhs, ")")
}

sum_to_zero_draw <- function(rhs, da, base, ctx) {
  if (da$name == "std_normal") return(paste0("(function(z) z - mean(z))(", rhs, ")"))
  if (!identical(da$values$mu$code, "0") || type_rank(da$values$sigma$type %||% list(base = "real", adims = 0L)) > 0) {
    stan2r_unsupported(sprintf("sum_to_zero_vector '%s' with a prior other than normal(0, scalar)", base),
                       ctx$line, "sum_to_zero_vector prior")
  }
  paste0("(function(z) z - mean(z))(", rhs, ")")
}

sampling_density_code <- function(outcome, dist, origin, suffix, args, truncation, ctx) {
  y <- translate_expr(outcome, ctx)
  scalar_outcome <- type_rank(outcome$type) == 0
  if (origin == "UserDefined") {
    fn <- paste0(dist, if (suffix == "FnLpmf") "_lpmf" else "_lpdf")
    if (!scalar_outcome) {
      stan2r_unsupported(sprintf("pointwise density of container outcome %s under user-defined %s",
                                 stan_expr_text(outcome), fn), ctx$line, "user-defined density of a container")
    }
    ctx$user_calls <- unique(c(ctx$user_calls, fn))
    vals <- vapply(args, function(a) translate_expr(a, ctx)$code, "")
    return(paste0(fn, "(", paste(c(y$code, vals), collapse = ", "), ")"))
  }
  if (is.null(stan_distributions()[[dist]]) && is.na(stan_glm_distributions[dist])) {
    stan2r_unsupported(sprintf("distribution %s", dist), ctx$line, paste0("distribution ", dist))
  }
  da <- distribution_args(dist, args, ctx)
  d <- fill_template(dist_template(da, "d", ctx), c(da$values, list(y = r_paren(y))))
  if (isTRUE(da$def$multivariate)) return(d)
  if (scalar_outcome && any(vapply(args, function(a) type_rank(a$type) > 0, logical(1)))) d <- paste0("sum(", d, ")")
  if (!is.null(truncation)) {
    p_tpl <- dist_template(da, "p", ctx)
    cdf <- function(at) fill_template(p_tpl, c(da$values, list(y = at, opts = "")))
    lower <- if (!is.null(truncation$lower)) translate_expr(truncation$lower, ctx) else NULL
    upper <- if (!is.null(truncation$upper)) translate_expr(truncation$upper, ctx) else NULL
    pl <- if (is.null(lower)) "0" else cdf(if (isTRUE(da$def$discrete)) paste0(wrap(lower, PREC_ADD), " - 1") else wrap(lower, PREC_ATOM))
    pu <- if (is.null(upper)) "1" else cdf(wrap(upper, PREC_ATOM))
    d <- paste0(d, " - log(", pu, " - ", pl, ")")
  }
  d
}

# target += ...: density terms, mixtures, and other increments
tr_target <- function(s, ctx, depth) {
  i <- ind(depth)
  e <- s$expr
  # accumulator reductions
  if (identical(e$node, "Call") && e$name %in% c("log_sum_exp", "sum") && length(e$args) == 1 &&
      identical(e$args[[1]]$node, "Var") && !is.null(ctx$accumulators[[e$args[[1]]$name]])) {
    return(tr_accumulator_target(s, ctx, depth, e$args[[1]]$name))
  }
  out <- character(0)
  for (t in sum_terms(e)) {
    x <- t$expr
    if (t$sign > 0 && is_lp_call(x)) {
      out <- c(out, tr_sampling(s, ctx, depth, outcome = x$args[[1]], dist = lp_call_dist(x), origin = x$origin,
                                suffix = x$suffix, args = x$args[-1], truncation = NULL))
    } else if (t$sign > 0 && identical(x$node, "Call") && x$name %in% c("log_sum_exp", "log_mix") && x$origin == "StanLib" &&
               length(ir_find(x, is_lp_call))) {
      out <- c(out, tr_mixture(s, ctx, depth, x))
    } else {
      out <- c(out, tr_other_target(s, ctx, depth, x))
    }
  }
  out
}

tr_other_target <- function(s, ctx, depth, x) {
  i <- ind(depth)
  deps <- expr_vars(x)
  if (identical(x$node, "Call") && x$name == "log_sum_exp" && length(x$args) == 1 && identical(x$args[[1]]$node, "Var") &&
      !(identical(x$ad, "DataOnly") && !any(deps %in% ctx$observed))) {
    stan2r_unsupported(sprintf(paste0("mixture accumulator '%s' whose elements are not assigned direct density terms ",
                                      "(write lp[k] = log_weight + dist_lpdf(y | ...))"), x$args[[1]]$name),
                       s$line, "mixture accumulator")
  }
  if (length(ir_find(x, is_lp_call))) {
    stan2r_unsupported("density term that is not a single added term of target", s$line, "density inside a larger expression")
  }
  if (!length(deps) || (identical(x$ad, "DataOnly") && !any(deps %in% ctx$observed))) {
    return(paste0(i, "# (constant target increment: ", stan_expr_text(x), ")"))
  }
  on_observed <- any(deps %in% ctx$observed)
  if (!on_observed && ctx$posterior) {
    return(paste0(i, "# (prior term, fixed by the posterior draw: target += ", stan_expr_text(x), ")"))
  }
  stan2r_unsupported(sprintf("target increment '%s' that is not a density statement", stan_expr_text(x)),
                     s$line, "free-form target increment")
}

mixture_components <- function(x, ctx) {
  if (x$name == "log_mix") {
    if (length(x$args) != 3 || type_rank(x$args[[1]]$type) != 0) {
      stan2r_unsupported("log_mix with vector arguments", ctx$line, "log_mix with vectors")
    }
    theta <- x$args[[1]]
    w1 <- list(node = "Call", name = "log", origin = "StanLib", suffix = "FnPlain", args = list(theta), type = theta$type, ad = theta$ad)
    w2 <- list(node = "Call", name = "log1m", origin = "StanLib", suffix = "FnPlain", args = list(theta), type = theta$type, ad = theta$ad)
    comps <- lapply(x$args[2:3], split_weight, ctx = ctx)
    comps[[1]]$weight <- if (is.null(comps[[1]]$weight)) w1 else rebuild_sum(list(list(expr = w1, sign = 1), list(expr = comps[[1]]$weight, sign = 1)))
    comps[[2]]$weight <- if (is.null(comps[[2]]$weight)) w2 else rebuild_sum(list(list(expr = w2, sign = 1), list(expr = comps[[2]]$weight, sign = 1)))
    return(comps)
  }
  lapply(x$args, split_weight, ctx = ctx)
}

tr_mixture <- function(s, ctx, depth, x) {
  i <- ind(depth)
  comps <- mixture_components(x, ctx)
  if (any(vapply(comps, is.null, logical(1)))) {
    stan2r_unsupported(sprintf("%s whose arguments are not all density terms", x$name), s$line, "mixture form")
  }
  outs <- unique(vapply(comps, function(cm) stan_expr_text(cm$call$args[[1]]), ""))
  if (length(outs) > 1) stan2r_unsupported("mixture over different outcomes", s$line, "mixture over several outcomes")
  outcome <- comps[[1]]$call$args[[1]]
  base <- outcome_base(outcome)
  if (is.null(base)) stan2r_unsupported("mixture with an expression outcome", s$line, "expression on left of ~")
  action <- sampling_action(sym_role(ctx, base), ctx)
  if (action == "skip") return(paste0(i, "# (prior mixture, fixed by the posterior draw: ", stan_stmt_text(s, ctx), ")"))
  if (action == "error") stan2r_unsupported(sprintf("mixture on '%s', which cannot be simulated forward", base), s$line, "~ on derived quantity")
  weights <- vapply(comps, function(cm) if (is.null(cm$weight)) "0" else translate_expr(cm$weight, ctx)$code, "")
  if (action == "draw") {
    ctx_use_helper(ctx, "softmax")
    is_param <- sym_role(ctx, base) == "param"
    draw_list <- lapply(comps, function(cm) sampling_draw_code(cm$call$args[[1]], lp_call_dist(cm$call), cm$call$origin,
                                                               cm$call$args[-1], NULL, ctx, implicit_bounds = is_param))
    draws <- vapply(draw_list, `[[`, "", "rhs")
    weights <- vapply(seq_along(comps), function(k) component_weight(weights[k], draw_list[[k]], ctx), "")
    lhs <- lvalue_code(outcome, ctx)
    return(c(paste0(i, "component__ <- sample.int(", length(comps), ", 1, prob = softmax(c(", paste(weights, collapse = ", "), ")))"),
             paste0(i, lhs, " <- switch(component__, ", paste(draws, collapse = ", "), ")")))
  }
  if (type_rank(outcome$type) > 0) {
    stan2r_unsupported("pointwise density of a mixture over a whole container", s$line, "mixture density of a container")
  }
  ctx_use_helper(ctx, c("log_sum_exp", "add_log_density"))
  dens <- vapply(seq_along(comps), function(k) {
    cm <- comps[[k]]
    d <- sampling_density_code(cm$call$args[[1]], lp_call_dist(cm$call), cm$call$origin, cm$call$suffix, cm$call$args[-1], NULL, ctx)
    if (weights[k] == "0") d else paste0(weights[k], " + ", d)
  }, "")
  target <- paste0("log_density__$", base, substring(lvalue_code(outcome, ctx), nchar(r_name(base)) + 1))
  paste0(i, target, " <- add_log_density(", target, ", log_sum_exp(", paste(dens, collapse = ", "), "))")
}

tr_accumulator_target <- function(s, ctx, depth, acc_name) {
  i <- ind(depth)
  acc <- ctx$accumulators[[acc_name]]
  role <- sym_role(ctx, acc$base)
  action <- sampling_action(role, ctx)
  if (action == "skip") return(paste0(i, "# (prior mixture, fixed by the posterior draw: ", stan_stmt_text(s, ctx), ")"))
  if (action == "error") stan2r_unsupported(sprintf("mixture on '%s', which cannot be simulated forward", acc$base), s$line, "~ on derived quantity")
  if (acc$reducer == "sum") {
    if (action == "draw") return(paste0(i, "# (", acc_name, " terms were drawn above: ", stan_stmt_text(s, ctx), ")"))
    stan2r_unsupported("pointwise densities through a sum() accumulator", s$line, "sum accumulator density")
  }
  if (action == "draw") {
    ctx_use_helper(ctx, "softmax")
    lhs <- lvalue_code(acc$outcome, ctx)
    return(c(paste0(i, "component__ <- sample.int(length(", acc_name, "), 1, prob = softmax(", acc_name, "))"),
             paste0(i, lhs, " <- ", acc_name, "_draws__[[component__]]")))
  }
  if (type_rank(acc$outcome$type) > 0) {
    stan2r_unsupported("pointwise density of a mixture over a whole container", s$line, "mixture density of a container")
  }
  ctx_use_helper(ctx, c("log_sum_exp", "add_log_density"))
  target <- paste0("log_density__$", acc$base, substring(lvalue_code(acc$outcome, ctx), nchar(r_name(acc$base)) + 1))
  paste0(i, target, " <- add_log_density(", target, ", log_sum_exp(", acc_name, "))")
}

#### blocks ####

translate_data_block <- function(ctx) {
  out <- character(0)
  for (s in ctx$program$blocks$data) {
    ctx$line <- s$line
    lead <- c(if (isTRUE(s$blank_before) && !length(s$comments_before)) "", comment_lines(s$comments_before, 0))
    code <- character(0)
    for (v in s$vars) {
      if (s$stype$base == "tuple") stan2r_unsupported("tuple data", s$line, "tuples")
      if (grepl("complex", s$stype$base)) stan2r_unsupported("complex data", s$line, "complex numbers")
      missing_from_dat <- !is.null(ctx$dat_names) && !(v$name %in% ctx$dat_names)
      simulated <- ctx$sim && v$name %in% ctx$observed
      if (missing_from_dat && !simulated) {
        stop(sprintf("Stan2R: data variable '%s' (line %d) is missing from dat", v$name, s$line), call. = FALSE)
      }
      rhs <- if (missing_from_dat) paste0(alloc_code(s$stype, ctx), "  # simulated below") else paste0("dat$", v$name)
      code <- c(code, paste0(r_name(v$name), " <- ", rhs))
    }
    if (length(s$comment_after) && length(code)) code[length(code)] <- paste0(code[length(code)], "  # ", paste(s$comment_after, collapse = " "))
    out <- c(out, lead, code)
  }
  out
}

translate_parameters <- function(ctx) {
  out <- character(0)
  for (s in ctx$program$blocks$parameters) {
    ctx$line <- s$line
    lead <- c(if (isTRUE(s$blank_before) && !length(s$comments_before)) "", comment_lines(s$comments_before, 0))
    code <- character(0)
    for (v in s$vars) {
      if (s$stype$base == "tuple") stan2r_unsupported("tuple parameters", s$line, "tuples")
      if (ctx$posterior) {
        code <- c(code, paste0(r_name(v$name), " <- ", draw_value_code(ctx$samps, ctx$sample_index, v$name, s, ctx)))
      } else {
        code <- c(code, paste0(r_name(v$name), " <- ", alloc_code(s$stype, ctx)))
        if (!(v$name %in% ctx$drawn_params)) code <- c(code, implicit_prior_draw(v$name, s, ctx))
      }
    }
    if (length(s$comment_after) && length(code)) code[length(code)] <- paste0(code[length(code)], "  # ", paste(s$comment_after, collapse = " "))
    out <- c(out, lead, code)
  }
  out
}

# parameters without a sampling statement: proper uniform priors on bounded supports
implicit_prior_draw <- function(name, s, ctx) {
  tr <- s$transform
  nm <- r_name(name)
  n <- if (type_rank(list(base = s$stype$base, adims = length(s$stype$array_dims))) == 0) "1" else paste0("length(", nm, ")")
  lhs <- if (length(s$stype$array_dims) + length(s$stype$dims) >= 2) paste0(nm, "[]") else nm
  if (tr$kind == "bounds" && !is.null(tr$lower) && !is.null(tr$upper)) {
    return(paste0(lhs, " <- runif(", n, ", ", translate_expr(tr$lower, ctx)$code, ", ", translate_expr(tr$upper, ctx)$code,
                  ")  # implicit uniform prior"))
  }
  one_draw <- function(like) switch(tr$kind,
    simplex = { ctx_use_helper(ctx, "rdirichlet"); paste0("rdirichlet(", like, ", 1)") },
    unit_vector = paste0("(function(z) z / sqrt(sum(z^2)))(rnorm(length(", like, ")))"),
    cholesky_factor_corr = { ctx_use_helper(ctx, "rlkj_corr_cholesky"); paste0("rlkj_corr_cholesky(", like, ", 1)") },
    corr_matrix = { ctx_use_helper(ctx, "rlkj_corr"); paste0("rlkj_corr(", like, ", 1)") },
    NULL)
  if (length(s$stype$array_dims) == 1 && !is.null(one_draw("x"))) {
    ctx$counter <- ctx$counter + 1L
    k <- paste0("i", ctx$counter, "__")
    elem <- paste0(nm, "[", k, strrep(", ", length(s$stype$dims)), "]")
    return(c(paste0("for (", k, " in seq_len(dim(", nm, ")[1])) {  # implicit uniform prior"),
             paste0("  ", elem, " <- ", one_draw(elem)), "}"))
  }
  if (length(s$stype$array_dims) == 0) {
    if (tr$kind == "simplex") {
      ctx_use_helper(ctx, "rdirichlet")
      return(paste0(nm, " <- rdirichlet(", nm, ", 1)  # implicit uniform prior"))
    }
    if (tr$kind == "unit_vector") return(paste0(nm, " <- (function(z) z / sqrt(sum(z^2)))(rnorm(length(", nm, ")))  # implicit uniform prior"))
    if (tr$kind == "cholesky_factor_corr") {
      ctx_use_helper(ctx, "rlkj_corr_cholesky")
      return(paste0(nm, " <- rlkj_corr_cholesky(", nm, ", 1)  # implicit uniform prior"))
    }
    if (tr$kind == "corr_matrix") {
      ctx_use_helper(ctx, "rlkj_corr")
      return(paste0(nm, " <- rlkj_corr(", nm, ", 1)  # implicit uniform prior"))
    }
  }
  if (ctx$mode %in% c("prior_predictive", "prior_density")) {
    # reported after the model block, whose errors are usually more specific
    ctx$improper <- c(ctx$improper, list(list(name = name, line = s$line)))
  }
  character(0)
}

# transformed parameters and model, reordered for prior simulation
translate_tp_and_model <- function(ctx) {
  tp <- ctx$program$blocks[["transformed parameters"]]
  model <- ctx$program$blocks$model
  density_init <- character(0)
  if (!ctx$sim && length(ctx$observed)) {
    ctx_use_helper(ctx, "add_log_density")
    density_init <- c("log_density__ <- list()",
                      unlist(lapply(ctx$observed, function(v) c(paste0("log_density__$", v, " <- ", r_name(v)),
                                                                 paste0("log_density__$", v, "[] <- NA_real_")))))
  }
  if (ctx$posterior) {
    secs <- list(list(label = "transformed parameters", lines = tr_stmts(tp, ctx, 0)),
                 list(label = "model", lines = c(density_init, tr_stmts(model, ctx, 0))))
    return(secs)
  }
  units <- c(lapply(tp, function(s) list(stmt = s, block = "transformed parameters")),
             lapply(model, function(s) list(stmt = s, block = "model")))
  if (!length(units)) return(list())
  order <- prior_schedule(units, ctx)
  secs <- list()
  seen_tp <- FALSE
  for (k in order) {
    u <- units[[k]]
    label <- u$block
    if (label == "model" && !seen_tp && all(unit_writes(u$stmt, ctx) %in% names(ctx$sym)[vapply(ctx$sym, `[[`, "", "role") == "param"]) &&
        length(unit_writes(u$stmt, ctx))) {
      label <- "parameters"
    }
    if (label == "transformed parameters") seen_tp <- TRUE
    lines <- tr_stmt_annotated(u$stmt, ctx, 0)
    if (length(secs) && secs[[length(secs)]]$label == label) {
      secs[[length(secs)]]$lines <- c(secs[[length(secs)]]$lines, lines)
    } else {
      if (label == "model" && length(density_init)) {
        lines <- c(density_init, lines)
        density_init <- character(0)
      }
      secs[[length(secs) + 1]] <- list(label = label, lines = lines)
    }
  }
  secs
}

#### prior-simulation scheduling ####

# reads/writes of a statement; names declared inside it are local to it
stmt_rw <- function(s, ctx) {
  reads <- character(0)
  writes <- character(0)
  local <- character(0)
  lp_writes <- function(x) {
    outs <- vapply(ir_find(x, is_lp_call), function(cl) outcome_base(cl$args[[1]]) %||% "", "")
    outs[outs != "" & vapply(outs, function(o) drawable_role(sym_role(ctx, o)), logical(1))]
  }
  visit <- function(s) {
    switch(s$node,
      Decl = {
        local <<- c(local, vapply(s$vars, `[[`, "", "name"))
        reads <<- c(reads, expr_vars(list(s$stype, s$transform, lapply(s$vars, `[[`, "init"))))
      },
      Assign = {
        b <- outcome_base(s$lhs)
        writes <<- c(writes, b)
        reads <<- c(reads, expr_vars(s$rhs), setdiff(expr_vars(s$lhs), b))
        if (s$lhs$node != "Var" || s$op != "=") reads <<- c(reads, b)
        writes <<- c(writes, lp_writes(s$rhs))
      },
      Tilde = {
        b <- outcome_base(s$arg)
        reads <<- c(reads, expr_vars(list(s$args, s$truncation)), setdiff(expr_vars(s$arg), b))
        if (!is.null(b) && drawable_role(sym_role(ctx, b))) writes <<- c(writes, b) else reads <<- c(reads, b)
      },
      TargetPE = {
        reads <<- c(reads, expr_vars(s$expr))
        writes <<- c(writes, lp_writes(s$expr))
        e <- s$expr
        if (identical(e$node, "Call") && length(e$args) == 1 && identical(e$args[[1]]$node, "Var")) {
          acc <- ctx$accumulators[[e$args[[1]]$name]]
          if (!is.null(acc)) writes <<- c(writes, acc$base)
        }
      },
      For = {
        reads <<- c(reads, expr_vars(list(s$lower, s$upper)))
        local <<- c(local, s$var)
        visit(s$body)
      },
      ForEach = {
        reads <<- c(reads, expr_vars(s$iter))
        local <<- c(local, s$var)
        visit(s$body)
      },
      While = { reads <<- c(reads, expr_vars(s$cond)); visit(s$body) },
      If = {
        reads <<- c(reads, expr_vars(s$cond))
        visit(s$then)
        if (!is.null(s$otherwise)) visit(s$otherwise)
      },
      Block = , Profile = for (k in s$stmts) visit(k),
      reads <<- c(reads, expr_vars(s)))
  }
  top_decl <- if (s$node == "Decl") vapply(s$vars, `[[`, "", "name") else character(0)
  visit(s)
  nested_local <- setdiff(local, top_decl)
  list(reads = setdiff(unique(reads), nested_local), writes = unique(c(setdiff(writes, nested_local), top_decl)))
}

unit_writes <- function(s, ctx) {
  w <- stmt_rw(s, ctx)$writes
  if (s$node == "Decl") character(0) else w
}

prior_schedule <- function(units, ctx) {
  n <- length(units)
  rw <- lapply(units, function(u) stmt_rw(u$stmt, ctx))
  simulated <- c(names(ctx$sym)[vapply(ctx$sym, function(x) x$role == "param", logical(1))], ctx$observed)
  before <- matrix(FALSE, n, n)
  for (i in seq_len(n)) for (j in seq_len(n)) {
    if (i == j) next
    wi <- rw[[i]]$writes; ri <- rw[[i]]$reads; wj <- rw[[j]]$writes; rj <- rw[[j]]$reads
    for (v in union(wi, ri)) {
      if (v %in% simulated) {
        if (v %in% wi && v %in% rj && !(v %in% wj)) before[i, j] <- TRUE
        if (v %in% wi && v %in% wj && i < j) before[i, j] <- TRUE
      } else if (i < j && ((v %in% wi && v %in% union(rj, wj)) || (v %in% ri && v %in% wj))) {
        before[i, j] <- TRUE
      }
    }
  }
  # prior draws of parameters first (as in the parameters block), then program order
  param_names <- names(ctx$sym)[vapply(ctx$sym, function(x) x$role == "param", logical(1))]
  is_prior_draw <- vapply(seq_len(n), function(k) {
    units[[k]]$block == "model" && length(rw[[k]]$writes) > 0 && all(rw[[k]]$writes %in% param_names)
  }, logical(1))
  priority <- order(!is_prior_draw, seq_len(n))
  done <- logical(n)
  order <- integer(0)
  while (length(order) < n) {
    ready <- which(!done & vapply(seq_len(n), function(j) !any(before[!done, j] & seq_len(n)[!done] != j), logical(1)))
    ready <- priority[priority %in% ready]
    if (!length(ready)) {
      left <- which(!done)
      lines <- vapply(units[left], function(u) as.character(u$stmt$line), "")
      stan2r_unsupported(sprintf(paste0("circular dependency between prior draws and derived quantities ",
                                        "(statements on lines %s); split the loop or reorder the model"),
                                 paste(lines, collapse = ", ")), units[[left[1]]]$stmt$line, "circular prior dependency")
    }
    k <- ready[1]
    done[k] <- TRUE
    order <- c(order, k)
  }
  order
}

#### output ####

output_lines <- function(ctx) {
  names <- ctx$program$symbols$name
  if (!length(names)) return("out <- list()")
  vals <- vapply(names, function(v) {
    if (!ctx$sim && v %in% ctx$observed) paste0(v, " = exp(log_density__$", v, ")") else paste0(v, " = ", r_name(v))
  }, "")
  vals <- ifelse(names %in% r_reserved, paste0("`", names, "`", sub("^[^ ]+", "", vals)), vals)
  wrapped <- wrap_items(vals, first = "out <- list(", indent = "  ", width = 90)
  wrapped[length(wrapped)] <- paste0(wrapped[length(wrapped)], ")")
  c(if (!ctx$sim && length(ctx$observed)) "# observed data are replaced by their pointwise densities (masses)", wrapped)
}

#### functions block ####

translate_functions <- function(ctx) {
  defs <- ctx$program$functions
  out <- list()
  for (nm in names(defs)) {
    f <- defs[[nm]]
    before <- ctx$user_calls
    ctx$user_calls <- character(0)
    res <- tryCatch({
      ctx$line <- f$line
      args <- vapply(f$args, function(a) r_name(a$name), "")
      body <- tr_body(f$body, ctx, 1)
      lines <- c(comment_lines(f$comments_before, 0),
                 paste0(r_name(nm), " <- function(", paste(args, collapse = ", "), ") {"), body, "}", "")
      list(lines = lines, error = NULL, calls = ctx$user_calls)
    }, stan2r_unsupported = function(e) list(lines = NULL, error = e, calls = character(0)))
    ctx$user_calls <- before
    out[[nm]] <- res
  }
  out
}

finish_functions <- function(ctx, fun) {
  if (!length(fun)) return(character(0))
  used <- intersect(ctx$user_calls, names(fun))
  repeat {
    more <- unique(unlist(lapply(fun[used], `[[`, "calls")))
    new <- setdiff(intersect(more, names(fun)), used)
    if (!length(new)) break
    used <- c(used, new)
  }
  out <- character(0)
  for (nm in names(fun)) {
    if (!(nm %in% used)) next
    if (!is.null(fun[[nm]]$error)) stop(fun[[nm]]$error)
    out <- c(out, fun[[nm]]$lines)
  }
  out
}

#### Stan text of IR (comments and messages) ####

stan_stmt_text <- function(s, ctx) {
  span <- s$span
  if (is.null(span)) return(s$node)
  txt <- substr(ctx$program$source_text, span[["start"]], span[["end"]])
  gsub("\\s+", " ", txt)
}

# join items with ", " into lines of at most `width` characters
wrap_items <- function(items, first = "", indent = "  ", width = 90) {
  lines <- character(0)
  current <- first
  for (k in seq_along(items)) {
    piece <- paste0(items[k], if (k < length(items)) "," else "")
    candidate <- if (current %in% c(first, indent)) paste0(current, piece) else paste(current, piece)
    if (nchar(candidate) > width && !(current %in% c(first, indent))) {
      lines <- c(lines, current)
      current <- paste0(indent, piece)
    } else {
      current <- candidate
    }
  }
  c(lines, current)
}

# target += log_sum_exp(lp) / sum(lp) (or `return ...` inside a user density)
accumulator_targets <- function(stmts, node = "TargetPE") {
  out <- list()
  walk_stmts(stmts, function(s) {
    if (s$node != node) return(invisible())
    e <- if (node == "TargetPE") s$expr else s$value
    if (identical(e$node, "Call") && e$name %in% c("log_sum_exp", "sum") && length(e$args) == 1 &&
        identical(e$args[[1]]$node, "Var")) {
      out[[e$args[[1]]$name]] <<- list(reducer = e$name, line = s$line)
    }
  })
  out
}

# accumulators: lp[k] = weight + D_lpdf(y | ...), later reduced by log_sum_exp(lp) or sum(lp)
find_accumulators <- function(stmts, acc_targets) {
  accs <- list()
  for (acc in names(acc_targets)) {
    sites <- list()
    walk_stmts(stmts, function(s) {
      if (s$node == "Assign" && identical(outcome_base(s$lhs), acc)) {
        calls <- ir_find(s$rhs, is_lp_call)
        if (length(calls)) sites[[length(sites) + 1]] <<- list(stmt = s, call = calls[[1]], n = length(calls))
      }
    })
    if (!length(sites)) next
    outs <- unique(vapply(sites, function(x) stan_expr_text(x$call$args[[1]]), ""))
    if (length(outs) > 1) {
      stan2r_unsupported(sprintf("accumulator '%s' mixes densities of different outcomes (%s)", acc,
                                 paste(outs, collapse = ", ")), acc_targets[[acc]]$line, "mixture over several outcomes")
    }
    if (any(vapply(sites, `[[`, 0L, "n") > 1)) {
      stan2r_unsupported(sprintf("more than one density term in one assignment to accumulator '%s'", acc),
                         sites[[1]]$stmt$line, "mixture accumulator")
    }
    accs[[acc]] <- list(reducer = acc_targets[[acc]]$reducer, outcome = sites[[1]]$call$args[[1]],
                        base = outcome_base(sites[[1]]$call$args[[1]]))
  }
  accs
}

#### user-defined densities without an _rng ####

# Simulate from a user-defined foo_lpdf(y | ...) by translating its body as a small
# model whose outcome is y: density terms on y become draws, `return lp` acts like
# `target += lp`. Returns the name of the generated R function.
derive_udf_draw <- function(dist, ctx) {
  fname <- paste0(dist, "_draw__")
  if (!is.null(ctx$derived_functions[[fname]])) return(fname)
  def <- ctx$program$functions[[paste0(dist, "_lpdf")]] %||% ctx$program$functions[[paste0(dist, "_lpmf")]]
  if (is.null(def)) {
    stan2r_unsupported(sprintf("user-defined distribution %s has no %s_rng() and no _lpdf/_lpmf body", dist, dist),
                       ctx$line, "user-defined distribution without _rng")
  }
  y <- def$args[[1]]$name
  saved <- mget(c("sym", "observed", "accumulators", "sim", "posterior", "derived_outcome", "line"), envir = ctx)
  on.exit(list2env(saved, envir = ctx), add = TRUE)
  args_sym <- lapply(def$args, function(a) list(name = a$name, role = if (a$name == y) "data" else "tdata"))
  names(args_sym) <- vapply(def$args, `[[`, "", "name")
  ctx$sym <- args_sym
  ctx$observed <- y
  ctx$sim <- TRUE
  ctx$posterior <- TRUE
  ctx$derived_outcome <- y
  body_stmts <- if (identical(def$body$node, "Block")) def$body$stmts else list(def$body)
  ctx$accumulators <- find_accumulators(body_stmts, accumulator_targets(body_stmts, "Return"))
  body <- tryCatch(tr_body(def$body, ctx, 1), stan2r_unsupported = function(e) {
    stan2r_unsupported(sprintf("cannot simulate from user-defined %s_lpdf (no %s_rng()): %s", dist, dist,
                               sub("^Stan2R: unsupported: ", "", conditionMessage(e))),
                       saved$line, "user-defined distribution without _rng")
  })
  args <- vapply(def$args, function(a) r_name(a$name), "")
  ctx$derived_functions[[fname]] <- c(
    sprintf("# draws %s from user-defined %s (derived from its density)", y, paste0(def$name, "()")),
    paste0(fname, " <- function(", paste(args, collapse = ", "), ") {"), body, "}", "")
  fname
}
